//! The names from before the rename to Atelier (formerly Copilot Canvas),
//! in one place. Old installs, scripts, scheduled entries, sessions, paired
//! clients and services of the previous build still use them, so the new
//! build reads, detects and migrates them (docs/DEVELOPMENT.md, *Renaming to
//! Atelier*). `tools/rename-to-atelier.py` never rewrites this file.

/// The product's former name.
pub const PRODUCT: &str = "Copilot Canvas";

/// The CLI's former name; sessions keep it as a deprecated alias of `atelier`.
pub const CLI: &str = "copilot-canvas";

/// The prefix of the former environment variables (`COPILOT_CANVAS_HOME`, …),
/// still read when the `ATELIER_` name is not set (`crate::env`).
pub const ENV_PREFIX: &str = "COPILOT_CANVAS_";

/// The variable a client puts in `AgentLaunch::env` for a launch's skill
/// folders: a wire constant (services of the previous build only know this
/// name, so clients keep sending it; services accept both).
pub const GROUP_SKILLS_ENV: &str = "COPILOT_CANVAS_GROUP_SKILLS";

/// The former data folder under the user's home (`~/.copilot-canvas`).
pub const HOME_DIR: &str = ".copilot-canvas";

/// The former service pipe on Windows: `\\.\pipe\copilot-canvas-<user>-<instance>-<hash>`.
pub const PIPE_PREFIX: &str = r"\\.\pipe\copilot-canvas-";

/// The former per-user socket folder (`<runtime or temp>/copilot-canvas-<user>`).
pub const SOCKET_DIR_PREFIX: &str = "copilot-canvas-";

/// The former per-build service copies (`<home>/bin/copilot-canvas-service-<build>`).
pub const SERVICE_COPY_PREFIX: &str = "copilot-canvas-service-";

/// The former prefix of the automations the product names itself
/// (`CopilotCanvas-Tunnel`, the README's `CopilotCanvas-Service`).
pub const TASK_PREFIX: &str = "CopilotCanvas-";

/// The folder of the former tunnel manifest (`<automations>/copilot-canvas/`).
pub const TUNNEL_MANIFEST_DIR: &str = "copilot-canvas";

/// The Dev Tunnel id used when `remote.tunnel` is not set: installs set up
/// before the rename host this tunnel, so it stays their default.
pub const DEFAULT_TUNNEL: &str = "copilot-canvas";

/// launchd: the former labels of automations and of the service at login.
pub const LAUNCHD_TASK_PREFIX: &str = "com.copilot-canvas.task.";
pub const LAUNCHD_SERVICE_LABEL: &str = "com.copilot-canvas.service";
/// launchd: the former prefix of the comment lines a task's plist carries
/// (`copilot-canvas-name: `, `copilot-canvas-manifest: `, `copilot-canvas-schedule: `).
pub const LAUNCHD_COMMENT_PREFIX: &str = "copilot-canvas-";

/// systemd: the former unit names (`copilot-canvas-task-<name>.{service,timer}`,
/// `copilot-canvas[-<instance>].service`, the transient `copilot-canvas-<instance>`).
pub const SYSTEMD_TASK_PREFIX: &str = "copilot-canvas-task-";
pub const SYSTEMD_SERVICE_UNIT: &str = "copilot-canvas";
/// systemd: the former prefix of the keys a task's units carry (`X-CopilotCanvas-Name=`).
pub const SYSTEMD_KEY_PREFIX: &str = "X-CopilotCanvas-";
/// systemd: the former description of a task without one.
pub const SYSTEMD_DESCRIPTION_SUFFIX: &str = " (Copilot Canvas automation)";

/// cron: the former block markers and task header.
pub const CRON_BEGIN: &str = "# >>> Copilot Canvas automations (generated from manifests: edit those, then run `copilot-canvas automations apply`) >>>";
pub const CRON_END: &str = "# <<< Copilot Canvas automations <<<";
pub const CRON_TASK: &str = "# copilot-canvas-task: ";

/// The macOS Keychain service and the Linux Secret Service application of a
/// home's master key before the rename (read when the new item is missing).
pub const KEYCHAIN_SERVICE: &str = "Copilot Canvas";
pub const SECRET_SERVICE_APPLICATION: &str = "copilot-canvas";

/// The first line of a todo board's Markdown mirror written before the rename.
pub const MIRROR_MARK: &str = "> Generated by Copilot Canvas";

/// The former pairing-link scheme the iPhone app still accepts.
pub const PAIR_SCHEME: &str = "ccanvas://pair";
